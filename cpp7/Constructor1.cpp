#include <iostream>
#include <string>
using namespace std;

// 생성자에 대해서 다룹니다.
// 생성자는 객체가 생성될 때 자동으로 호출되는 특별한 멤버 함수입니다.
// 생성자의 이름은 클래스의 이름과 동일하며 반환형이 없습니다.

class Person {
public:
    string name;
    int age;

    // 생성자: 클래스 이름과 똑같고, 반환 타입이 없는 함수
    // 생성자의 이름은 클래스 이름과 동일해야 하며, 반환형이 없습니다.
    // 생성자는 객체가 생성될 때 자동으로 호출됩니다.
    // 생성자는 객체의 초기화를 담당합니다.
    // 생성자는 매개변수를 가질 수 있으며, 이를 통해 객체를 초기화할 수 있습니다.
    // 생성자는 오버로딩이 가능합니다. 즉, 같은 이름의 생성자를 여러 개 정의할 수 있습니다.
    // 생성자는 반환 값이 없기 때문에 void를 명시하지 않습니다.
    Person(string n, int a) {
        name = n;
        age = a;
    }

    // 기본 생성자: 매개변수가 없는 생성자
    // 오버로딩된 생성자가 하나라도 존재하면, 컴파일러는 기본 생성자를 자동으로 제공하지 않습니다.
    // 따라서 기본 생성자를 명시적으로 정의해야 합니다.
    Person() {
        name = "이름 없음";
        age = 0;
    }

    void introduce() {
        cout << "안녕하세요, 제 이름은 " << name << "이고, 나이는 " << age << "살입니다." << endl;
    }
};

int main() {
    // Person 객체 생성 시 생성자가 자동으로 호출됩니다.
    Person person1("홍길동", 30);
    person1.introduce();

    Person person2("김철수", 25);
    person2.introduce();

    Person person3; // 기본 생성자 호출
    person3.introduce();

    return 0;
}

/*
안녕하세요, 제 이름은 홍길동이고, 나이는 30살입니다.
안녕하세요, 제 이름은 김철수이고, 나이는 25살입니다.
안녕하세요, 제 이름은 이름 없음이고, 나이는 0살입니다.
*/